"""Write the SSUS bid-rent diagram as a Hugo partial of inline SVG.

Run from the repo root: python tools/make_bidrent.py layouts/partials/bidrent-svg.html

Three linear bid-rent curves R_i(d) = A_i - t_i |d|, symmetric about the
market center. Each use wins where its bid is highest; land rent is the upper
envelope. Colors come from CSS classes (series slots 1-3), so the page's
light and dark themes restyle it.
"""
import sys

CX, GROUND, W = 320.0, 300.0, 300.0
USES = [  # name, class, rent at the center (px), distance where the bid reaches zero (px)
    ("Commercial", "x", 250.0, 125.0),
    ("Residential", "y", 160.0, 250.0),
    ("Agriculture", "z", 95.0, 300.0),
]
slope = {c: A / z for _, c, A, z in USES}
peak = {c: A for _, c, A, _ in USES}
rent = lambda c, d: max(0.0, peak[c] - slope[c] * d)
Y = lambda r: GROUND - r
cross = lambda c1, c2: (peak[c1] - peak[c2]) / (slope[c1] - slope[c2])
a, b = cross("x", "y"), cross("y", "z")
c = W
f = lambda v: f"{v:.1f}"
pt = lambda x, y: f"{f(x)},{f(y)}"

out = []
o = out.append
o('{{/* Generated by make_bidrent.py (bid rent after von Thünen and Alonso, redrawn from the book). Edit the script, not this file. */}}')
o('<svg class="bidrent" viewBox="0 0 640 372" role="img" aria-labelledby="bidrent-title bidrent-desc">')
o('  <title id="bidrent-title">Bid-rent curves around a market center</title>')
o(f'  <desc id="bidrent-desc">Three bid-rent lines fall with distance from the market center. Commercial bids are highest and steepest and win out to distance a; residential bids win from a to b; agricultural bids, lowest and flattest, win from b to c. Land rent follows the upper envelope of the three lines.</desc>')
# zone fills under the envelope
o('  <g class="br-zones">')
o(f'    <polygon class="br-fill-x" points="{pt(CX-a,GROUND)} {pt(CX-a,Y(rent("x",a)))} {pt(CX,Y(peak["x"]))} {pt(CX+a,Y(rent("x",a)))} {pt(CX+a,GROUND)}"/>')
for s in (1, -1):
    o(f'    <polygon class="br-fill-y" points="{pt(CX+s*a,GROUND)} {pt(CX+s*a,Y(rent("y",a)))} {pt(CX+s*b,Y(rent("y",b)))} {pt(CX+s*b,GROUND)}"/>')
    o(f'    <polygon class="br-fill-z" points="{pt(CX+s*b,GROUND)} {pt(CX+s*b,Y(rent("z",b)))} {pt(CX+s*c,GROUND)}"/>')
o('  </g>')
# each bid line in full, faint and dashed where it loses
o('  <g class="br-bids">')
for _, cl, A, z in USES:
    o(f'    <polyline class="br-{cl}" points="{pt(CX-z,GROUND)} {pt(CX,Y(A))} {pt(CX+z,GROUND)}"/>')
o('  </g>')
# boundaries a and b
o('  <g class="br-guides">')
for s in (1, -1):
    o(f'    <line x1="{f(CX+s*a)}" y1="{f(GROUND)}" x2="{f(CX+s*a)}" y2="{f(Y(rent("x",a)))}"/>')
    o(f'    <line x1="{f(CX+s*b)}" y1="{f(GROUND)}" x2="{f(CX+s*b)}" y2="{f(Y(rent("y",b)))}"/>')
o('  </g>')
# winning segments: the envelope, in each use's color
o('  <g class="br-env">')
o(f'    <polyline class="br-x" points="{pt(CX-a,Y(rent("x",a)))} {pt(CX,Y(peak["x"]))} {pt(CX+a,Y(rent("x",a)))}"/>')
for s in (1, -1):
    o(f'    <polyline class="br-y" points="{pt(CX+s*a,Y(rent("y",a)))} {pt(CX+s*b,Y(rent("y",b)))}"/>')
    o(f'    <polyline class="br-z" points="{pt(CX+s*b,Y(rent("z",b)))} {pt(CX+s*c,GROUND)}"/>')
o('  </g>')
# axes
o('  <g class="br-axes">')
o(f'    <line x1="{f(CX-W)}" y1="{f(GROUND)}" x2="{f(CX+W)}" y2="{f(GROUND)}"/>')
o(f'    <line x1="{f(CX)}" y1="{f(GROUND)}" x2="{f(CX)}" y2="36"/>')
o('  </g>')
# labels
o('  <g class="br-labels">')
o(f'    <text class="br-axis-label" x="{f(CX)}" y="24" text-anchor="middle">Land rent</text>')
for s in (1, -1):
    for lab, d in (("a", a), ("b", b), ("c", c - 4 if s == 1 else c - 4)):
        o(f'    <text class="br-tick" x="{f(CX+s*d)}" y="321" text-anchor="middle">{lab}</text>')
o(f'    <text class="br-axis-label" x="{f(CX)}" y="352" text-anchor="middle">Market center</text>')
o(f'    <text class="br-name br-name-x" x="{f(CX+a*0.62+12)}" y="{f(Y(rent("x",a*0.62))-4)}">Commercial</text>')
dy = (a + b) / 2
o(f'    <text class="br-name br-name-y" x="{f(CX+dy+10)}" y="{f(Y(rent("y",dy))-8)}">Residential</text>')
o(f'    <text class="br-name br-name-z" x="{f(CX+b+6)}" y="{f(Y(rent("z",b))-12)}">Agriculture</text>')
o('  </g>')
# distance arrows
o('  <g class="br-arrows">')
o(f'    <line x1="{f(CX-72)}" y1="347" x2="{f(CX-W+6)}" y2="347"/><polyline points="{pt(CX-W+14,342)} {pt(CX-W+6,347)} {pt(CX-W+14,352)}"/>')
o(f'    <line x1="{f(CX+72)}" y1="347" x2="{f(CX+W-6)}" y2="347"/><polyline points="{pt(CX+W-14,342)} {pt(CX+W-6,347)} {pt(CX+W-14,352)}"/>')
o('  </g>')
o('</svg>')
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(f"a={a:.1f} b={b:.1f} rent(a)={rent('x', a):.1f} rent(b)={rent('y', b):.1f}")
